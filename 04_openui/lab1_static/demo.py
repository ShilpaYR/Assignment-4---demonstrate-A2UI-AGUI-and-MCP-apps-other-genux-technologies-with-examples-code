"""Recorded demo for OpenUI lab 1 (static): pre-built components chosen in OpenUI Lang."""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path[:0] = [str(HERE.parents[1]), str(HERE)]

from common.demo import banner, browser_page, compact, post, snap, start  # noqa: E402
from common.web import read_sse  # noqa: E402
import server  # noqa: E402
import oui  # noqa: E402


def main():
    banner("Part 4 / Lab 4.1 - OpenUI Lang static: a library of pre-built components")
    sig = [l for l in server.SYSTEM.splitlines() if "(" in l and ") —" in l]
    print("prompt generated by library.prompt(); component signatures:")
    for line in sig:
        print("  | " + line[:110])
    url = start(server.build_app())
    events = read_sse(post(f"{url}/oui/stream", {}))
    program = "".join(e.get("delta", "") for e in events)
    print(f"model output ({len(events) - 1} chunks):")
    for line in program.splitlines():
        print("  " + (line if len(line) < 112 else line[:109] + "..."))
    print("server summary:", compact(events[-1], 140))
    res = oui.official_parse(program, "static")
    if res:
        print(f"official parser: {res['elements']} elements, errors={res['meta']['errors']}, unresolved={res['meta']['unresolved']}")
    print("action restock_beans -> edit:", json.loads(post(f"{url}/oui/action", {"action": "restock_beans"}))["patch"].strip())
    with browser_page() as page:
        if page:
            page.goto(url)
            page.wait_for_selector("text=the model only chose")
            page.click("[data-action=restock_beans]")
            page.wait_for_selector("text=13.5 kg")
            snap(page, HERE, "screenshot.png")


if __name__ == "__main__":
    main()
