"""Part 4 / Lab 1 - OpenUI Lang, STATIC mode: the library holds only pre-built components.

OpenUI Lang (thesys, ``@openuidev/lang-core``) is a compact, line-oriented
language for UIs: ``name = Component(arg1, arg2, ...)``. Which components
exist is decided by a *library*. In static mode the library contains only
high-level, pre-built pieces:

    SalesDashboard(title, revenue, revenueDelta, cups, avgTicket, days, dailyRevenue, topItems)
    InventoryCard(beansKg, reorderKg)

so the model can only pick them and fill their positional arguments. The
page owns how they look (``page/app.js``). The prompt is generated by the
library itself (``library.prompt()``).

Actions use OpenUI's edit model: the server answers with *new statements*
(``stock = InventoryCard(13.5, 5)``) that the page merges into the program
with ``mergeStatements``.

    python server.py            # http://127.0.0.1:8041
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SHARED = HERE.parent / "shared"
sys.path[:0] = [str(HERE.parents[1]), str(SHARED)]

import oui  # noqa: E402
from common import scenario, tokens  # noqa: E402
from common.llm import get_llm  # noqa: E402
from common.web import SSE, App, sse_frame  # noqa: E402

PORT = 8041
LIBRARY = "static"
SYSTEM = oui.prompt(LIBRARY) + f"\n\nData:\n{scenario.as_text()}\nDaily revenue: {scenario.week_revenue()}"
llm = get_llm(HERE / "fixtures")


def frames(prompt: str):
    text = ""
    for chunk in llm.stream(system=SYSTEM, user=prompt, fixture="dashboard"):
        text += chunk
        yield sse_frame({"delta": chunk})
    errors = oui.check(text, LIBRARY)                 # the official parser, run once the program is complete
    yield sse_frame({"done": True, "errors": errors, "statements": len(oui.statements(text)),
                     "tokens": tokens.count(text), "token_method": tokens.method()}, event="genux")


def handle_action(body: dict) -> dict:
    if body.get("action") != "restock_beans":
        return {"error": f"unknown action {body.get('action')!r}"}
    beans = scenario.INVENTORY["beans_kg"] + 10
    return {"patch": f"stock = InventoryCard({beans}, {scenario.INVENTORY['reorder_point_kg']})\n"}


def build_app() -> App:
    app = App(HERE / "page", title="OpenUI lab 1 (static)")
    app.mount("oui", SHARED)

    @app.post("/oui/stream")
    def stream(req):
        return SSE(frames((req.json() or {}).get("prompt") or scenario.DASHBOARD_PROMPT))

    @app.post("/oui/action")
    def action(req):
        return handle_action(req.json())

    return app


if __name__ == "__main__":
    cli = argparse.ArgumentParser()
    cli.add_argument("--port", type=int, default=PORT)
    build_app().serve(cli.parse_args().port)
